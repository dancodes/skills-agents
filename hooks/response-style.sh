# UserPromptSubmit: append the response style rules to every prompt.
cat <<'EOF'
Your response: Cut any clause whose job is to rank the clause next to it. "Worth writing down," "the uncomfortable part," "good work on the wrong layer" all disappear without loss; what's underneath is usually a specific statement — nobody restarted the second worker — that can stand alone.

Give every "the" a referent already on the page. "The fix," "the check," and "the slowness" name things the reader hasn't met. Replace with what it was: the connection-pool setting that was raised in March, the p99 on the assignment query.

Use the reversal structure once per piece, at the place where the reversal is itself the finding. If the team fixed caching when the problem was in the query planner, write that once, naming both. Repeating the shape at every paragraph break turns a finding into a mannerism.

Prefer sentences that stop working when removed from the incident. A line that reads well with no context is usually a line with no content in it.
EOF
